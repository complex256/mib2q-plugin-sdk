#!/usr/bin/env bash
# Pull the stock HMI files needed for an SDK build off a MHI2Q unit.
#
#   tools/pull-stock-jars.sh <unit-host>
#
# Environment:
#   MIBSDK_HOST       the unit host when no argument is given
#   MIBSDK_STOCK_DIR  destination (default: build/stock)
#   JXE2JAR_SRC       path to the jxe2jar "src" directory; when set, lsd.jxe is converted to lsd.jar
#
# Nothing is committed. Audi's binaries stay on your machine.
set -euo pipefail

HOST="${1:-${MIBSDK_HOST:-}}"
DEST="${MIBSDK_STOCK_DIR:-build/stock}"
JXE2JAR_SRC="${JXE2JAR_SRC:-}"

die() { echo "pull-stock-jars: $*" >&2; exit 1; }
info() { echo "pull-stock-jars: $*" >&2; }

if [ -z "$HOST" ]; then
  die "usage: tools/pull-stock-jars.sh <unit-host>   (or set MIBSDK_HOST)"
fi
case "$HOST" in
  -*|*[!A-Za-z0-9._:-]*) die "invalid host '$HOST'" ;;
esac

SSH_OPTS=(-o HostKeyAlgorithms=ssh-rsa -o PubkeyAcceptedKeyTypes=ssh-rsa -o BatchMode=yes
          -o ConnectTimeout=8 -o ServerAliveInterval=5 -o ServerAliveCountMax=3)

rsh() { ssh "${SSH_OPTS[@]}" "root@$HOST" "$@"; }

info "connecting to root@$HOST"
rsh "echo ok" >/dev/null 2>&1 </dev/null || die "cannot reach root@$HOST over SSH"

mkdir -p "$DEST"

fetch() {
  local remote="$1" local="$2"
  info "copying $remote"
  rsh "cat '$remote'" > "$local" </dev/null || die "could not read $remote"
  [ -s "$local" ] || die "$remote is empty"
  chmod 0644 "$local"
}

fetch /ifs/lsd.jxe "$DEST/lsd.jxe"
fetch /mnt/app/eso/hmi/lsd/DSITracer.jar "$DEST/DSITracer.jar"
fetch /ifs/version_info.txt "$DEST/version_info.txt" || true

if [ "${MIBSDK_WITH_JARS:-}" = "1" ]; then
  mkdir -p "$DEST/jars"
  while IFS= read -r remote; do
    [ -n "$remote" ] || continue
    fetch "$remote" "$DEST/jars/$(basename "$remote")"
  done < <(rsh "find /mnt/app/eso/hmi/lsd/jars -maxdepth 1 -type f -name '*.jar'" </dev/null || true)
fi

if [ -n "$JXE2JAR_SRC" ]; then
  [ -f "$JXE2JAR_SRC/jxe2jar.py" ] || die "JXE2JAR_SRC must name the jxe2jar src directory (jxe2jar.py not found)"
  info "converting lsd.jxe with jxe2jar"
  PYTHONPATH="$JXE2JAR_SRC" python3 "$JXE2JAR_SRC/jxe2jar.py" "$DEST/lsd.jxe" "$DEST/lsd.jar" \
    || die "jxe2jar failed (it needs Python 3.10+ and bitstring==3.1.9)"
  [ -s "$DEST/lsd.jar" ] || die "jxe2jar wrote no lsd.jar"
else
  info "lsd.jxe downloaded; convert it with jxe2jar and set JXE2JAR_SRC next time, or run:"
  info "  PYTHONPATH=<jxe2jar>/src python3 <jxe2jar>/src/jxe2jar.py $DEST/lsd.jxe $DEST/lsd.jar"
fi

cat > "$DEST/gradle.properties" <<PROPS
# Generated by tools/pull-stock-jars.sh. Add these lines to \$GRADLE_USER_HOME/gradle.properties,
# or pass them with -P on the command line. Never commit them.
mibsdk.stockDsiTracerJar=$(cd "$DEST" && pwd)/DSITracer.jar
PROPS
if [ -s "$DEST/lsd.jar" ]; then
  echo "mibsdk.stockLsdJar=$(cd "$DEST" && pwd)/lsd.jar" >> "$DEST/gradle.properties"
fi

echo
echo "Stock files are in $DEST"
ls -lh "$DEST"
echo
echo "Next:"
echo "  cat $DEST/gradle.properties >> \"\${GRADLE_USER_HOME:-$HOME/.gradle}/gradle.properties\""
echo "  ./gradlew :dist:mibpkgPackage"
